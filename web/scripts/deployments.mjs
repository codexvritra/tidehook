// Computes the deterministic CREATE2 deployment for the whole tidehook stack on Robinhood Chain.
// Reads Foundry artifacts (`forge build` first) and writes:
//   ../deployments/robinhood.json   addresses, salts, init code hashes (committed, auditable)
//   src/lib/deployments.ts          addresses the app reads
//   src/deploy/initcode.json        salt + init code per contract, for the in-browser Deploy page
// Hooks need addresses whose low 14 bits equal their permission flags, so their salts are mined.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { concat, encodeAbiParameters, getContractAddress, keccak256, numberToHex, padHex } from "viem";

const POOL_MANAGER = "0x8366a39CC670B4001A1121B8F6A443A643e40951";
const CREATE2_DEPLOYER = "0x4e59b44847b379578588920cA78FbF26c0B4956C";
const ZERO = "0x0000000000000000000000000000000000000000";

const FLAG = {
  beforeInitialize: 1 << 13,
  afterInitialize: 1 << 12,
  beforeSwap: 1 << 7,
  afterSwap: 1 << 6,
  beforeSwapReturnsDelta: 1 << 3,
  afterSwapReturnsDelta: 1 << 2,
};
// Every hook charges launchpad fees through swap return-deltas.
const FEES = FLAG.beforeSwap | FLAG.afterSwap | FLAG.beforeSwapReturnsDelta | FLAG.afterSwapReturnsDelta;

const FILE = { TideTokenFactory: "TideToken" };
const artifact = (name) =>
  JSON.parse(readFileSync(new URL(`../../out/${FILE[name] ?? name}.sol/${name}.json`, import.meta.url))).bytecode.object;

function initCode(name, types, values) {
  if (types.length === 0) return artifact(name);
  return concat([artifact(name), encodeAbiParameters(types.map((type) => ({ type })), values)]);
}

function mine(code, flags) {
  const hash = keccak256(code);
  for (let i = 0n; i < 2_000_000n; i++) {
    const salt = padHex(numberToHex(i), { size: 32 });
    const address = getContractAddress({ from: CREATE2_DEPLOYER, opcode: "CREATE2", salt, bytecodeHash: hash });
    if ((parseInt(address.slice(-4), 16) & 0x3fff) === flags) return { salt, address };
  }
  throw new Error("no salt found");
}

function fixed(code, salt = padHex("0x0", { size: 32 })) {
  const address = getContractAddress({ from: CREATE2_DEPLOYER, opcode: "CREATE2", salt, bytecodeHash: keccak256(code) });
  return { salt, address };
}

const plan = [];
const add = (name, code, flags) => {
  const { salt, address } = flags === undefined ? fixed(code) : mine(code, flags);
  plan.push({ name, address, salt, initCode: code, initCodeHash: keccak256(code) });
  return address;
};

const patience = add(
  "PatienceHook",
  initCode("PatienceHook", ["address", "uint24", "uint24", "uint32", "uint32", "uint32"], [POOL_MANAGER, 10_000, 500, 30, 3600, 86_400]),
  FLAG.beforeInitialize | FEES,
);
const spring = add(
  "SpringHook",
  initCode(
    "SpringHook",
    ["address", "uint24", "uint24", "uint24", "uint24", "uint24", "uint32"],
    [POOL_MANAGER, 3000, 500, 50_000, 50, 20, 3600],
  ),
  FLAG.beforeInitialize | FLAG.afterInitialize | FEES,
);
const bond = add("CreatorBondHook", initCode("CreatorBondHook", ["address"], [POOL_MANAGER]), FLAG.beforeInitialize | FEES);
const session = add(
  "SessionHook",
  initCode("SessionHook", ["address", "address"], [POOL_MANAGER, ZERO]),
  FLAG.beforeInitialize | FEES,
);
const pot = add("TidePotHook", initCode("TidePotHook", ["address"], [POOL_MANAGER]), FLAG.beforeInitialize | FEES);
const factory = add("TideTokenFactory", initCode("TideTokenFactory", [], []));
const migrator = add(
  "TideMigrator",
  initCode("TideMigrator", ["address", "address", "address", "address", "address", "address"], [POOL_MANAGER, patience, spring, bond, session, pot]),
);
const launcher = add(
  "TideLauncher",
  initCode(
    "TideLauncher",
    ["address", "address", "address", "address", "address", "address", "address", "address"],
    [POOL_MANAGER, factory, migrator, patience, spring, bond, session, pot],
  ),
);
const router = add("TideRouter", initCode("TideRouter", ["address"], [POOL_MANAGER]));
const orders = add("TideOrders", initCode("TideOrders", ["address"], [POOL_MANAGER]));

mkdirSync(new URL("../../deployments/", import.meta.url), { recursive: true });
mkdirSync(new URL("../src/deploy/", import.meta.url), { recursive: true });

writeFileSync(
  new URL("../../deployments/robinhood.json", import.meta.url),
  JSON.stringify(
    {
      chainId: 4663,
      poolManager: POOL_MANAGER,
      create2Deployer: CREATE2_DEPLOYER,
      contracts: Object.fromEntries(plan.map((p) => [p.name, { address: p.address, salt: p.salt, initCodeHash: p.initCodeHash }])),
    },
    null,
    2,
  ) + "\n",
);

writeFileSync(
  new URL("../src/deploy/initcode.json", import.meta.url),
  JSON.stringify(plan.map(({ name, address, salt, initCode }) => ({ name, address, salt, initCode }))),
);

writeFileSync(
  new URL("../src/lib/deployments.ts", import.meta.url),
  `// Generated by scripts/deployments.mjs. Deterministic CREATE2 addresses on Robinhood Chain (4663).
import type { Address } from "viem";

export const ADDR = {
  patience: "${patience}",
  spring: "${spring}",
  bond: "${bond}",
  session: "${session}",
  pot: "${pot}",
  factory: "${factory}",
  migrator: "${migrator}",
  launcher: "${launcher}",
  router: "${router}",
  orders: "${orders}",
} as const satisfies Record<string, Address>;
`,
);

for (const p of plan) console.log(p.name.padEnd(16), p.address, p.salt);
