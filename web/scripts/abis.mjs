// Regenerates src/lib/abis.ts from Foundry build output (`forge build` first).
// Only the functions the site calls are kept, plus every custom error so reverts decode nicely.
import { readFileSync, writeFileSync } from "node:fs";

const USED = {
  PatienceHook: ["commit", "commitmentOf", "commitments", "feeForAge", "ageOf", "initializedAt"],
  SpringHook: ["quoteFee", "restLimit", "springs"],
  CreatorBondHook: ["bond", "claim", "slash", "claimable", "slashable", "heldFor", "bonds"],
  SessionHook: ["currentFee", "sessionAt", "fees", "schedule"],
};

let out = "// Generated by scripts/abis.mjs from forge build output. Do not edit.\n\n";
for (const [name, fns] of Object.entries(USED)) {
  const { abi } = JSON.parse(readFileSync(new URL(`../../out/${name}.sol/${name}.json`, import.meta.url)));
  const kept = abi.filter((e) => e.type === "error" || (e.type === "function" && fns.includes(e.name)));
  out += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(kept)} as const;\n\n`;
}
writeFileSync(new URL("../src/lib/abis.ts", import.meta.url), out);
console.log("wrote src/lib/abis.ts");
