// Regenerates src/lib/abis.ts from Foundry build output (`forge build` first).
// Keeps the functions and events the app uses, plus every custom error so reverts decode to names.
import { readFileSync, writeFileSync } from "node:fs";

const USED = {
  TideLauncher: ["launch", "getLaunch", "getLaunches", "launchCount", "collectFees", "poolIdOf", "launchIdPlusOne", "Launched", "FeesCollected"],
  TideRouter: ["swapExactIn", "quoteExactIn", "Trade"],
  PatienceHook: ["commit", "commitmentOf", "commitments", "feeForAge", "ageOf", "initializedAt", "baseFee", "minFee", "minAge", "rampDuration", "maxAge"],
  SpringHook: ["quoteFee", "restLimit", "springs", "baseFee", "minFee", "maxFee", "band", "stiffness"],
  CreatorBondHook: ["getBond", "claim", "slash", "claimable", "slashable", "heldFor", "vested"],
  SessionHook: ["currentFee", "sessionAt", "fees", "schedule", "owner"],
  TideToken: ["balanceOf", "allowance", "approve", "decimals", "symbol", "name", "totalSupply"],
};

let out = "// Generated by scripts/abis.mjs from forge build output. Do not edit.\n\n";
for (const [name, keep] of Object.entries(USED)) {
  const { abi } = JSON.parse(readFileSync(new URL(`../../out/${name}.sol/${name}.json`, import.meta.url)));
  const kept = abi.filter((e) => e.type === "error" || keep.includes(e.name));
  const missing = keep.filter((k) => !kept.some((e) => e.name === k));
  if (missing.length) throw new Error(`${name}: missing ${missing.join(", ")}`);
  out += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(kept)} as const;\n\n`;
}
// Uniswap v4 wraps every hook revert in CustomRevert.WrappedError; decoding it lets the app show the hook's reason.
out += `export const wrappedErrorAbi = [{"type":"error","name":"WrappedError","inputs":[{"name":"target","type":"address"},{"name":"selector","type":"bytes4"},{"name":"reason","type":"bytes"},{"name":"details","type":"bytes"}]}] as const;
`;
writeFileSync(new URL("../src/lib/abis.ts", import.meta.url), out);
console.log("wrote src/lib/abis.ts");
