// Regenerates src/lib/stocks.ts: the pair assets offered at launch (ETH + the tokenized stocks and USDG that
// pons.family offers), each verified on-chain, with the deepest hookless ETH/<asset> Uniswap v4 pool
// as its migration route. Run against mainnet: `node scripts/stocks.mjs`.
import { writeFileSync } from "node:fs";
import { createPublicClient, http, parseAbiItem, erc20Abi, keccak256, encodeAbiParameters, numberToHex } from "viem";

const pub = createPublicClient({ transport: http("https://rpc.mainnet.chain.robinhood.com", { retryCount: 8, retryDelay: 2000 }) });
const PM = "0x8366a39CC670B4001A1121B8F6A443A643e40951";
const STOCK_FACTORY = "0x4783C67b63dE2B358Ac5951a7D41F47A38F3C046"; // deploys every Robinhood stock token
const Z = "0x0000000000000000000000000000000000000000";
const INIT = parseAbiItem(
  "event Initialize(bytes32 indexed id, address indexed currency0, address indexed currency1, uint24 fee, int24 tickSpacing, address hooks, uint160 sqrtPriceX96, int24 tick)",
);
const EXT = parseAbiItem("function extsload(bytes32) view returns (bytes32)");
const ASSETS = [
  ["USDG", "0x5fc5360D0400a0Fd4f2af552ADD042D716F1d168"],
  ["NVDA", "0xd0601ce157db5bdc3162bbac2a2c8af5320d9eec"],
  ["SPY", "0x117cc2133c37b721f49de2a7a74833232b3b4c0c"],
  ["TSLA", "0x322f0929c4625ed5bad873c95208d54e1c003b2d"],
  ["GME", "0x1b0e319c6a659f002271b69db8a7df2f911c153e"],
  ["PLTR", "0x894e1ec2d74ffe5aef8dc8a9e84686accb964f2a"],
  ["GLD", "0xc9a981fee1f9dec688bb123ccdecc63d0debfc4e"],
  ["SPCX", "0x4a0e65a3eccec6dbe60ae065f2e7bb85fae35eea"],
  ["MU", "0xff080c8ce2e5feadaca0da81314ae59d232d4afd"],
];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Every stock token's address, straight from the factory's events.
const head = await pub.getBlockNumber();
const factoryAddrs = new Set();
for (let to = head; ; to -= 10_000_000n) {
  const from = to >= 9_999_999n ? to - 9_999_999n : 0n;
  for (const l of await pub.getLogs({ address: STOCK_FACTORY, fromBlock: from, toBlock: to })) {
    for (const t of l.topics.slice(1)) if (/^0x0{24}/.test(t)) factoryAddrs.add(("0x" + t.slice(26)).toLowerCase());
    for (const m of l.data.slice(2).match(/.{64}/g) ?? []) if (/^0{24}[0-9a-f]{40}$/i.test(m) && !/^0{64}$/.test(m)) factoryAddrs.add(("0x" + m.slice(24)).toLowerCase());
  }
  if (from === 0n) break;
}

const out = [];
for (const [ticker, address] of ASSETS) {
  const [symbol, name, decimals] = await Promise.all(
    ["symbol", "name", "decimals"].map((f) => pub.readContract({ address, abi: erc20Abi, functionName: f })),
  );
  if (symbol !== ticker) throw new Error(`${address} is ${symbol}, expected ${ticker}`);
  const stock = factoryAddrs.has(address.toLowerCase());
  if (ticker !== "USDG" && !stock) throw new Error(`${ticker} was not deployed by the Robinhood stock factory`);

  const pools = [];
  for (let to = head; ; to -= 10_000_000n) {
    const from = to >= 9_999_999n ? to - 9_999_999n : 0n;
    pools.push(...(await pub.getLogs({ address: PM, event: INIT, args: { currency0: Z, currency1: address }, fromBlock: from, toBlock: to })));
    await sleep(120);
    if (from === 0n) break;
  }
  let best = null;
  for (const p of pools.filter((x) => x.args.hooks === Z)) {
    const base = BigInt(keccak256(encodeAbiParameters([{ type: "bytes32" }, { type: "uint256" }], [p.args.id, 6n])));
    const v = await pub.readContract({ address: PM, abi: [EXT], functionName: "extsload", args: [numberToHex(base + 3n, { size: 32 })] });
    const liq = BigInt(v) & ((1n << 128n) - 1n);
    if (!best || liq > best.liq) best = { liq, fee: p.args.fee, tickSpacing: p.args.tickSpacing };
    await sleep(80);
  }
  console.log(ticker.padEnd(5), name, "| route:", best ? `fee ${best.fee} spacing ${best.tickSpacing}` : "none");
  out.push({
    symbol,
    name: name.replace(/ • Robinhood Token$/, ""),
    address,
    decimals: Number(decimals),
    stock,
    route: best && best.liq > 0n ? { currency0: Z, currency1: address, fee: best.fee, tickSpacing: best.tickSpacing, hooks: Z } : null,
  });
}

writeFileSync(
  new URL("../src/lib/stocks.ts", import.meta.url),
  `// Generated by scripts/stocks.mjs from Robinhood Chain mainnet. Do not edit by hand.
// Pair assets offered at launch: tokenized stocks (deployed by the Robinhood stock factory ${STOCK_FACTORY})
// and USDG, each with the deepest hookless ETH/<asset> Uniswap v4 pool used as its migration route.
import type { Address } from "viem";
import type { PoolKey } from "./data";

export type PairAsset = { symbol: string; name: string; address: Address; decimals: number; stock: boolean; route: PoolKey | null };

export const PAIR_ASSETS: PairAsset[] = ${JSON.stringify(out, null, 2)};
`,
);
console.log("wrote src/lib/stocks.ts");
